import {
  AlertTriangle,
  Bot,
  Code2,
  Key,
  Send,
  Sparkles,
  Terminal,
} from 'lucide-react'
import React, { useEffect, useRef, useState } from 'react'
import { kernelClient } from '../../kernel/kernelClient'
import { useOsStore } from '../../state/osStore'

interface ChatMessage {
  id: string
  role: 'user' | 'assistant'
  content: string
  engine: string
  commandSnippet?: string
  codeFile?: { path: string; code: string }
}

const INITIAL_MESSAGES: ChatMessage[] = [
  {
    id: 'msg-welcome',
    role: 'assistant',
    engine: 'Strata Kernel Intelligence',
    content:
      'Welcome to **Strata Copilot v1.0.0 ("Bedrock")**. I am wired directly to your in-browser **Linux 7.3.4 (`unkernel`)** environment, `/usr/local/bin/strataget`, and **Strata Studio**.\n\nUse the 1-click actions below any code block to **Run in Terminal** or **Apply to Strata Studio**, or click **Explain Last Error** in the toolbar to inspect live kernel diagnostics.',
    commandSnippet: 'strataget update && strataget list',
    codeFile: {
      path: '/root/system_audit.sh',
      code: `#!/bin/sh
echo "=== StrataOS v1.0.0 Bedrock System Audit ==="
uname -a
df -h /data
strataget list
`,
    },
  },
]

function synthesizeLocalResponse(prompt: string): {
  text: string
  commandSnippet?: string
  codeFile?: { path: string; code: string }
} {
  const lower = prompt.toLowerCase()
  if (lower.includes('error') || lower.includes('dmesg') || lower.includes('diagnos')) {
    return {
      text:
        '### Kernel & Filesystem Diagnostic Analysis\n\n1. **Cross-Origin Isolation (`COOP`/`COEP`)**: Verified active (`SharedArrayBuffer` zero-copy enabled).\n2. **Persistent Block Device (`/dev/wda`)**: Mounted as `ext4` at `/data` via IndexedDB (`kwdisk:kwdata-v1`).\n3. **Recommended Verification Command**: Run an integrity check on `/etc/strata/installed.json` and flush dirty `ext4` blocks.',
      commandSnippet: 'sync && cat /etc/strata/installed.json && dmesg | tail -n 10',
      codeFile: {
        path: '/root/diagnose_kernel.sh',
        code: `#!/bin/sh
echo "[Diag] Checking mounted ext4 persistence..."
mount | grep /data
echo "[Diag] Installed strataget packages:"
cat /etc/strata/installed.json
`,
      },
    }
  }

  if (lower.includes('wasm') || lower.includes('strataget') || lower.includes('package')) {
    return {
      text:
        '### Installing & Running WebAssembly Packages with `strataget`\n\nStrataOS uses `/etc/strata/installed.json` and `/opt/strata/apps/<pkg>/` as the single source of truth. You can install GUI and WASI CLI packages directly from the shell:',
      commandSnippet: 'strataget install hexforge && strataget install calcwasm && calcwasm "2^16 + sqrt(144)"',
      codeFile: {
        path: '/root/wasm_demo.sh',
        code: `#!/bin/sh
strataget update
strataget install hexforge
strataget install calcwasm
calcwasm "fib(20) + 0xFF"
`,
      },
    }
  }

  return {
    text:
      `### Automated Solution for: *"${prompt}"*\n\nHere is a ready-to-run shell script tailored for **StrataOS v1.0.0 ("Bedrock")** on Linux 7.3.4 (` +
      '`arch/wasm`' +
      `). Click **Run in Terminal** to execute immediately or **Apply to Strata Studio** to edit in the multi-pane IDE.`,
    commandSnippet: 'uname -a && ls -la /opt/strata/apps /root',
    codeFile: {
      path: '/root/copilot_task.sh',
      code: `#!/bin/sh
# Generated by Strata Copilot for: ${prompt.replace(/\n/g, ' ')}
echo "Executing task on $(uname -sr)..."
ls -la /root /opt/strata/apps
`,
    },
  }
}

export const StrataCopilot: React.FC = () => {
  const openApp = useOsStore((s) => s.openApp)
  const setStudioDraft = useOsStore((s) => s.setStudioDraft)
  const lastTerminalError = useOsStore((s) => s.lastTerminalError)

  const [messages, setMessages] = useState<ChatMessage[]>(INITIAL_MESSAGES)
  const [input, setInput] = useState('')
  const [isStreaming, setIsStreaming] = useState(false)
  const [chromeAiAvailable, setChromeAiAvailable] = useState(false)
  const [byokOpen, setByokOpen] = useState(false)
  const [apiKey, setApiKey] = useState('')
  const [apiEndpoint, setApiEndpoint] = useState('https://api.openai.com/v1/chat/completions')
  const [apiModel, setApiModel] = useState('gpt-4o-mini')

  const scrollRef = useRef<HTMLDivElement | null>(null)

  // Detect Chrome Built-in AI (window.LanguageModel or window.ai.languageModel)
  useEffect(() => {
    const win = window as unknown as {
      LanguageModel?: { availability?: () => Promise<string>; create?: () => Promise<unknown> }
      ai?: { languageModel?: { create?: () => Promise<unknown> } }
    }
    if (win.LanguageModel || win.ai?.languageModel) {
      setChromeAiAvailable(true)
    }
  }, [])

  useEffect(() => {
    scrollRef.current?.scrollTo({ top: scrollRef.current.scrollHeight, behavior: 'smooth' })
  }, [messages])

  const sendPrompt = async (promptText: string) => {
    const clean = promptText.trim()
    if (!clean || isStreaming) return

    const userMsg: ChatMessage = {
      id: `user-${Date.now()}`,
      role: 'user',
      content: clean,
      engine: 'User',
    }
    setMessages((prev) => [...prev, userMsg])
    setInput('')
    setIsStreaming(true)

    const assistantId = `ast-${Date.now()}`
    let engineUsed = chromeAiAvailable
      ? 'Chrome Built-in AI (Gemini Nano)'
      : apiKey.trim()
      ? `BYOK (${apiModel})`
      : 'Strata Local Kernel Engine'

    setMessages((prev) => [
      ...prev,
      {
        id: assistantId,
        role: 'assistant',
        content: 'Thinking...',
        engine: engineUsed,
      },
    ])

    try {
      let fullText = ''
      let cmdSnippet: string | undefined
      let codeFile: { path: string; code: string } | undefined

      const win = window as unknown as {
        LanguageModel?: {
          create: () => Promise<{ prompt: (q: string) => Promise<string> }>
        }
        ai?: {
          languageModel?: {
            create: () => Promise<{ prompt: (q: string) => Promise<string> }>
          }
        }
      }

      if (chromeAiAvailable && (win.LanguageModel?.create || win.ai?.languageModel?.create)) {
        try {
          const createFn = win.LanguageModel?.create ?? win.ai?.languageModel?.create
          const session = await createFn!()
          fullText = await session.prompt(
            `You are Strata Copilot inside StrataOS v1.0.0 (Linux 7.3.4 unkernel + strataget). Answer concisely: ${clean}`
          )
        } catch {
          const local = synthesizeLocalResponse(clean)
          fullText = local.text
          cmdSnippet = local.commandSnippet
          codeFile = local.codeFile
        }
      } else if (apiKey.trim()) {
        const res = await fetch(apiEndpoint, {
          method: 'POST',
          headers: {
            'Content-Type': 'application/json',
            Authorization: `Bearer ${apiKey.trim()}`,
          },
          body: JSON.stringify({
            model: apiModel,
            messages: [
              {
                role: 'system',
                content:
                  'You are Strata Copilot inside StrataOS v1.0.0 (Linux 7.3.4 unkernel + strataget). Be concise and include practical shell commands.',
              },
              { role: 'user', content: clean },
            ],
          }),
        })
        if (!res.ok) throw new Error(`API HTTP ${res.status}`)
        const data = (await res.json()) as {
          choices?: Array<{ message?: { content?: string } }>
        }
        fullText = data.choices?.[0]?.message?.content ?? 'No response returned.'
        const local = synthesizeLocalResponse(clean)
        cmdSnippet = local.commandSnippet
        codeFile = local.codeFile
      } else {
        const local = synthesizeLocalResponse(clean)
        fullText = local.text
        cmdSnippet = local.commandSnippet
        codeFile = local.codeFile
      }

      // Stream tokens smoothly
      const words = fullText.split(' ')
      let acc = ''
      for (let i = 0; i < words.length; i += 3) {
        acc += (i === 0 ? '' : ' ') + words.slice(i, i + 3).join(' ')
        const currentText = acc
        setMessages((prev) =>
          prev.map((m) =>
            m.id === assistantId
              ? {
                  ...m,
                  content: currentText,
                  commandSnippet: cmdSnippet,
                  codeFile,
                }
              : m
          )
        )
        await new Promise((r) => setTimeout(r, 18))
      }
    } catch (err) {
      const msg = err instanceof Error ? err.message : String(err)
      setMessages((prev) =>
        prev.map((m) =>
          m.id === assistantId ? { ...m, content: `Error: ${msg}` } : m
        )
      )
    } finally {
      setIsStreaming(false)
    }
  }

  const handleExplainLastError = async () => {
    const logs = await kernelClient.getDmesgLogs()
    const recentWarnOrErr =
      logs
        .slice()
        .reverse()
        .find((l) => l.level === 'err' || l.level === 'warn')?.raw ??
      lastTerminalError ??
      '[    0.522385] EXT4-fs (wda): mounted filesystem r/w with ordered data mode.'

    await sendPrompt(`Explain last kernel/terminal diagnostic log: ${recentWarnOrErr}`)
  }

  const handleRunInTerminal = (cmd: string) => {
    openApp('terminal')
    setTimeout(() => {
      kernelClient.sendCommandToTerminal(cmd)
    }, 120)
  }

  const handleApplyToStudio = async (file: { path: string; code: string }) => {
    await kernelClient.writeFileText(file.path, file.code)
    setStudioDraft({ filePath: file.path, content: file.code })
    openApp('studio', { filePath: file.path })
  }

  return (
    <div className="flex h-full flex-col bg-[#121215] text-zinc-100 select-none">
      {/* Top Engine & 1-Click Diagnostic Toolbar */}
      <div className="flex flex-wrap items-center justify-between gap-2 border-b border-white/10 bg-[#1c1c21] px-4 py-2 text-xs">
        <div className="flex items-center gap-2">
          <Bot className="h-4 w-4 text-cyan-400" />
          <span className="font-semibold">Strata Copilot</span>
          <span className="rounded bg-zinc-900 border border-white/10 px-2 py-0.5 font-mono text-[10px] text-cyan-300">
            {chromeAiAvailable
              ? 'Chrome Built-in AI (LanguageModel)'
              : apiKey.trim()
              ? `BYOK (${apiModel})`
              : 'Built-in Kernel Specialist'}
          </span>
        </div>

        <div className="flex items-center gap-1.5">
          <button
            id="copilot-explain-error-btn"
            onClick={() => void handleExplainLastError()}
            className="inline-flex items-center gap-1 rounded border border-amber-500/30 bg-amber-500/15 px-2.5 py-1 text-xs font-medium text-amber-300 hover:bg-amber-500/25"
          >
            <AlertTriangle className="h-3.5 w-3.5" /> Explain Last Error
          </button>
          <button
            onClick={() => setByokOpen((o) => !o)}
            className="inline-flex items-center gap-1 rounded border border-white/10 bg-zinc-900 px-2.5 py-1 text-xs text-zinc-300 hover:bg-zinc-800"
          >
            <Key className="h-3.5 w-3.5 text-cyan-400" /> BYOK Config
          </button>
        </div>
      </div>

      {/* BYOK Configuration Drawer */}
      {byokOpen && (
        <div className="border-b border-white/10 bg-[#1c1c21]/90 p-3 text-xs space-y-2">
          <div className="font-semibold text-cyan-300">
            Chrome Built-in AI (`window.LanguageModel`) + BYOK Fallback Settings
          </div>
          <div className="grid grid-cols-1 md:grid-cols-3 gap-2">
            <input
              type="text"
              value={apiEndpoint}
              onChange={(e) => setApiEndpoint(e.target.value)}
              placeholder="OpenAI-compatible endpoint"
              className="rounded border border-white/10 bg-[#09090b] px-2.5 py-1 font-mono text-xs text-zinc-200"
            />
            <input
              type="text"
              value={apiModel}
              onChange={(e) => setApiModel(e.target.value)}
              placeholder="Model (e.g. gpt-4o-mini)"
              className="rounded border border-white/10 bg-[#09090b] px-2.5 py-1 font-mono text-xs text-zinc-200"
            />
            <input
              type="password"
              value={apiKey}
              onChange={(e) => setApiKey(e.target.value)}
              placeholder="API Key (sk-...)"
              className="rounded border border-white/10 bg-[#09090b] px-2.5 py-1 font-mono text-xs text-zinc-200"
            />
          </div>
        </div>
      )}

      {/* Messages Stream */}
      <div ref={scrollRef} className="flex-1 overflow-y-auto p-4 space-y-4 select-text">
        {messages.map((m) => (
          <div
            key={m.id}
            className={`rounded-xl border p-3.5 text-xs ${
              m.role === 'user'
                ? 'ml-10 border-cyan-500/30 bg-cyan-950/20 text-zinc-100'
                : 'mr-4 border-white/10 bg-[#1c1c21] text-zinc-200'
            }`}
          >
            <div className="mb-1.5 flex items-center justify-between text-[10px] font-mono text-zinc-400">
              <span className="font-semibold uppercase text-cyan-300">
                {m.role === 'user' ? 'You' : 'Strata Copilot'}
              </span>
              <span>{m.engine}</span>
            </div>

            <div className="whitespace-pre-wrap leading-relaxed">{m.content}</div>

            {m.codeFile && (
              <div className="mt-3 overflow-hidden rounded-lg border border-white/10 bg-[#09090b]">
                <div className="flex items-center justify-between border-b border-white/10 bg-[#121215] px-3 py-1 font-mono text-[11px] text-zinc-400">
                  <span>{m.codeFile.path}</span>
                  <span className="text-cyan-400">sh / bash</span>
                </div>
                <pre className="overflow-x-auto p-3 font-mono text-xs text-cyan-200">
                  {m.codeFile.code}
                </pre>
              </div>
            )}

            {/* 1-Click Actions */}
            {(m.commandSnippet || m.codeFile) && (
              <div className="mt-3 flex flex-wrap items-center gap-2 border-t border-white/10 pt-2.5">
                {m.commandSnippet && (
                  <button
                    onClick={() => handleRunInTerminal(m.commandSnippet!)}
                    className="inline-flex items-center gap-1.5 rounded bg-emerald-500/20 border border-emerald-500/40 px-2.5 py-1 text-xs font-semibold text-emerald-300 hover:bg-emerald-500/30"
                  >
                    <Terminal className="h-3.5 w-3.5" /> Run in Terminal
                  </button>
                )}
                {m.codeFile && (
                  <button
                    onClick={() => void handleApplyToStudio(m.codeFile!)}
                    className="inline-flex items-center gap-1.5 rounded bg-cyan-500/20 border border-cyan-500/40 px-2.5 py-1 text-xs font-semibold text-cyan-300 hover:bg-cyan-500/30"
                  >
                    <Code2 className="h-3.5 w-3.5" /> Apply to Strata Studio
                  </button>
                )}
              </div>
            )}
          </div>
        ))}
      </div>

      {/* Prompt Bar */}
      <div className="border-t border-white/10 bg-[#1c1c21] p-3">
        <div className="mb-2 flex flex-wrap gap-1.5">
          {[
            'Install & benchmark WASM packages with strataget',
            'Audit persistent ext4 filesystem & kernel dmesg',
            'Scaffold a new WASI CLI tool in Strata Studio',
          ].map((suggestion) => (
            <button
              key={suggestion}
              onClick={() => void sendPrompt(suggestion)}
              className="inline-flex items-center gap-1 rounded-full border border-white/10 bg-[#121215] px-2.5 py-0.5 text-[11px] text-zinc-300 hover:border-cyan-500/40 hover:text-cyan-300"
            >
              <Sparkles className="h-3 w-3 text-cyan-400" />
              {suggestion}
            </button>
          ))}
        </div>

        <div className="flex items-center gap-2">
          <input
            type="text"
            value={input}
            onChange={(e) => setInput(e.target.value)}
            onKeyDown={(e) => {
              if (e.key === 'Enter') void sendPrompt(input)
            }}
            placeholder="Ask Strata Copilot about Linux 7.3.4, strataget packages, or shell scripts..."
            className="flex-1 rounded-lg border border-white/10 bg-[#09090b] px-3 py-2 text-xs text-zinc-100 placeholder-zinc-500 focus:border-cyan-500 focus:outline-none"
          />
          <button
            onClick={() => void sendPrompt(input)}
            disabled={isStreaming}
            className="inline-flex items-center gap-1.5 rounded-lg bg-cyan-500 px-4 py-2 text-xs font-semibold text-zinc-950 hover:bg-cyan-400 disabled:opacity-50"
          >
            <Send className="h-3.5 w-3.5" />
            Send
          </button>
        </div>
      </div>
    </div>
  )
}
